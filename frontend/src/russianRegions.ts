export const RUSSIAN_REGIONS: RegionInfo[] = SUBJECTS_DATA.flatMap(([regionName, tzLabel, cities]) =>
  cities.map(([cityName, lat, lng, keywords]) => ({
    value: cityName,
    label: cityName.includes(regionName)
      ? cityName
      : `${cityName} (${regionName})`,
    regionName,
    tzLabel,
    lat,
    lng,
    keywords: `${cityName} ${regionName} ${keywords || ''}`.toLowerCase().replace(/ё/g, 'е'),
  }))
);

export function getRegionInfo(cityOrRegion?: string): RegionInfo | undefined {
  if (!cityOrRegion) return undefined;
  const norm = cityOrRegion.trim().toLowerCase().replace(/ё/g, 'е');
  if (norm === 'онлайн' || norm === 'online') return undefined;

  // 1. Exact value match
  const exact = RUSSIAN_REGIONS.find(
    (r) => r.value.toLowerCase().replace(/ё/g, 'е') === norm
  );
  if (exact) return exact;

  // 2. Match by region name (returns the administrative capital / first city of that region)
  const byRegion = RUSSIAN_REGIONS.find(
    (r) => r.regionName.toLowerCase().replace(/ё/g, 'е') === norm
  );
  if (byRegion) return byRegion;

  // 3. Partial / substring match
  return RUSSIAN_REGIONS.find(
    (r) =>
      r.label.toLowerCase().replace(/ё/g, 'е').includes(norm) ||
      (r.keywords && r.keywords.includes(norm))
  );
}

export function searchRussianLocations(query: string): RegionInfo[] {
  const q = query.trim().toLowerCase().replace(/ё/g, 'е');
  if (!q) return RUSSIAN_REGIONS;

  const tokens = q.split(/\s+/).filter(Boolean);
  const scored: Array<{ item: RegionInfo; score: number }> = [];

  for (const r of RUSSIAN_REGIONS) {
    const valNorm = r.value.toLowerCase().replace(/ё/g, 'е');
    const regNorm = r.regionName.toLowerCase().replace(/ё/g, 'е');
    const haystack = r.keywords || `${valNorm} ${regNorm}`;

    const allMatched = tokens.every((t) => haystack.includes(t));
    if (!allMatched) continue;

    let score = 10;
    if (valNorm === q) score = 100;
    else if (valNorm.startsWith(q)) score = 80;
    else if (regNorm.startsWith(q) || regNorm.includes(q)) score = 60;

    scored.push({ item: r, score });
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.map((s) => s.item);
}
